"""vanir-os attestation, host side: check TPM quotes, compare them with an approved reference,
and seal the storage master key to an attested guest. Used by verify-quote.py and host-agent.py."""
import hashlib
import struct

from cryptography.exceptions import InvalidSignature
from cryptography.hazmat.primitives import hashes, serialization
from cryptography.hazmat.primitives.asymmetric import ec
from cryptography.hazmat.primitives.asymmetric.utils import encode_dss_signature
from cryptography.hazmat.primitives.asymmetric.x25519 import X25519PrivateKey, X25519PublicKey
from cryptography.hazmat.primitives.ciphers.aead import ChaCha20Poly1305
from cryptography.hazmat.primitives.kdf.hkdf import HKDF

TPM_GENERATED = 0xFF544347
ST_ATTEST_QUOTE = 0x8018
PCRS = ["0", "4", "7", "12", "13"]


class Reader:
    def __init__(self, data):
        self.data, self.at = data, 0

    def take(self, n):
        if self.at + n > len(self.data):
            raise ValueError("TPMS_ATTEST is truncated")
        b = self.data[self.at:self.at + n]
        self.at += n
        return b

    def u8(self):
        return self.take(1)[0]

    def u16(self):
        return struct.unpack(">H", self.take(2))[0]

    def u32(self):
        return struct.unpack(">I", self.take(4))[0]

    def sized(self):
        return self.take(self.u16())


def parse_attest(blob):
    r = Reader(blob)
    if r.u32() != TPM_GENERATED:
        raise ValueError("not generated by a TPM")
    if r.u16() != ST_ATTEST_QUOTE:
        raise ValueError("not a quote")
    r.sized()  # qualifiedSigner
    extra = r.sized()
    r.take(8 + 4 + 4 + 1)  # clockInfo
    r.take(8)  # firmwareVersion
    selected = []
    for _ in range(r.u32()):
        r.u16()  # hash algorithm
        bits = r.take(r.u8())
        selected += [i for i in range(8 * len(bits)) if bits[i // 8] >> (i % 8) & 1]
    digest = r.sized()
    return extra, [str(p) for p in selected], digest


def runtime_entry(e):
    """The kernel's 80-byte run-time log entry (kernel/src/measure.rs) for a JSON entry."""
    op = {"load": 1, "unload": 2}[e["op"]]
    return (bytes([op, e["slot"]]) + bytes(6) + e["name"].encode().ljust(32, b"\0")
            + struct.pack("<Q", e["version"]) + bytes.fromhex(e["statement"]))


def replay_runtime(entries):
    """PCR 13 after extending with each run-time log entry."""
    pcr = bytes(32)
    for e in entries:
        pcr = hashlib.sha256(pcr + hashlib.sha256(runtime_entry(e)).digest()).digest()
    return pcr


def check(quote, nonce, tamper=False, runtime=()):
    """Return the problems with `quote` as a quote over `nonce` (empty if none). A quote that
    carries a key-exchange public key (`kx_pub`) must be over SHA-256(nonce || kx_pub).
    `runtime` holds the run-time log entries sent after the quote; they must replay to PCR 13.
    With `runtime=None` PCR 13 isn't checked (the caller didn't get the log)."""
    problems = []
    attest = bytearray.fromhex(quote["attest"])
    if tamper:
        attest[-1] ^= 1  # for tests: a quote changed after the TPM signed it
    try:
        extra, selected, pcr_digest = parse_attest(bytes(attest))
    except ValueError as e:
        return [str(e)]
    expected = bytes.fromhex(nonce)
    if "kx_pub" in quote:
        expected = hashlib.sha256(expected + bytes.fromhex(quote["kx_pub"])).digest()
    if extra != expected:
        problems.append("the quote is not over this challenge's nonce (replayed?)")
    key = ec.EllipticCurvePublicNumbers(int(quote["ak_x"], 16), int(quote["ak_y"], 16), ec.SECP256R1()).public_key()
    signature = encode_dss_signature(int(quote["sig_r"], 16), int(quote["sig_s"], 16))
    try:
        key.verify(signature, bytes(attest), ec.ECDSA(hashes.SHA256()))
    except InvalidSignature:
        problems.append("the signature does not verify")
    if selected != PCRS:
        problems.append(f"quoted PCRs {selected}, expected {PCRS}")
    reported = b"".join(bytes.fromhex(quote["pcrs"][p]) for p in PCRS)
    if hashlib.sha256(reported).digest() != pcr_digest:
        problems.append("the reported PCR values are not the ones the TPM signed")
    pcr12 = bytes(32)
    for entry in quote["log"]:
        pcr12 = hashlib.sha256(pcr12 + bytes.fromhex(entry["digest"])).digest()
    if pcr12.hex() != quote["pcrs"]["12"]:
        problems.append("the measurement log does not replay to PCR 12")
    count = quote.get("runtime_count", 0)
    if runtime is None:
        pass
    elif len(runtime) != count:
        problems.append(f"the quote covers {count} run-time log entries; {len(runtime)} arrived")
    elif replay_runtime(runtime).hex() != quote["pcrs"]["13"]:
        problems.append("the run-time log does not replay to PCR 13")
    return problems



PCR_NAMES = {"0": "firmware", "4": "boot loader", "7": "Secure Boot state", "12": "kernel/manifest/tasks",
             "13": "images loaded at run time"}


def compare(quote, reference):
    """Problems with `quote` against an approved reference (empty if none)."""
    problems = []
    if (quote["ak_x"], quote["ak_y"]) != (reference["ak_x"], reference["ak_y"]):
        problems.append("signed by a different attestation key than the reference")
    for pcr, want in reference["pcrs"].items():
        if quote["pcrs"][pcr] != want:
            problems.append(f"PCR {pcr} ({PCR_NAMES[pcr]}) differs from the reference")
    return problems


def seal_key(master_key, kx_pub_hex, nonce_hex):
    """Seal `master_key` (32 bytes) to the guest's X25519 key for this challenge: returns the hex
    the guest's `key` command takes (our public key, ciphertext, tag)."""
    ours = X25519PrivateKey.generate()
    shared = ours.exchange(X25519PublicKey.from_public_bytes(bytes.fromhex(kx_pub_hex)))
    nonce = bytes.fromhex(nonce_hex)
    key = HKDF(algorithm=hashes.SHA256(), length=32, salt=nonce, info=b"vanir key release").derive(shared)
    sealed = ChaCha20Poly1305(key).encrypt(bytes(12), master_key, nonce)
    public = ours.public_key().public_bytes(serialization.Encoding.Raw, serialization.PublicFormat.Raw)
    return (public + sealed).hex()
