#!/usr/bin/env python3
"""Verify a vanir-os TPM quote from the telemetry log against an approved reference.

  verify-quote.py --log build/telemetry.log --record REF --expected-pcr12 HEX
      Check a known-good boot's quote and save it as the reference: the attestation key (trusted
      on first use), PCRs 0, 4, 7 (firmware, boot loader, Secure Boot state) as observed, and
      PCR 12 as computed from the approved build (tools/expected-pcrs.py).

  verify-quote.py --log build/telemetry.log --reference REF
      Check a later boot's quote: signed by the reference key, over the nonce the host sent,
      with exactly the reference PCR values.

Checks: TPMS_ATTEST is TPM-generated and a quote; its extraData is the challenge nonce; the
ECDSA P-256 signature verifies; its PCR digest matches the reported PCR values; the kernel's
measurement log replays to the reported PCR 12.
"""
import argparse
import hashlib
import json
import struct
import sys

from cryptography.exceptions import InvalidSignature
from cryptography.hazmat.primitives import hashes
from cryptography.hazmat.primitives.asymmetric import ec
from cryptography.hazmat.primitives.asymmetric.utils import encode_dss_signature

TPM_GENERATED = 0xFF544347
ST_ATTEST_QUOTE = 0x8018
PCRS = ["0", "4", "7", "12"]


class Reader:
    def __init__(self, data):
        self.data, self.at = data, 0

    def take(self, n):
        if self.at + n > len(self.data):
            raise ValueError("TPMS_ATTEST is truncated")
        b = self.data[self.at:self.at + n]
        self.at += n
        return b

    def u8(self):
        return self.take(1)[0]

    def u16(self):
        return struct.unpack(">H", self.take(2))[0]

    def u32(self):
        return struct.unpack(">I", self.take(4))[0]

    def sized(self):
        return self.take(self.u16())


def parse_attest(blob):
    r = Reader(blob)
    if r.u32() != TPM_GENERATED:
        raise ValueError("not generated by a TPM")
    if r.u16() != ST_ATTEST_QUOTE:
        raise ValueError("not a quote")
    r.sized()  # qualifiedSigner
    extra = r.sized()
    r.take(8 + 4 + 4 + 1)  # clockInfo
    r.take(8)  # firmwareVersion
    selected = []
    for _ in range(r.u32()):
        r.u16()  # hash algorithm
        bits = r.take(r.u8())
        selected += [i for i in range(8 * len(bits)) if bits[i // 8] >> (i % 8) & 1]
    digest = r.sized()
    return extra, [str(p) for p in selected], digest


def last(records, event):
    found = [r for r in records if r.get("event") == event]
    if not found:
        sys.exit(f"verify-quote: FAIL: no {event} record in the log")
    return found[-1]


def check(quote, nonce, tamper=False):
    """Return the problems with `quote` as a quote over `nonce` (empty if none)."""
    problems = []
    attest = bytearray.fromhex(quote["attest"])
    if tamper:
        attest[-1] ^= 1  # for tests: a quote changed after the TPM signed it
    try:
        extra, selected, pcr_digest = parse_attest(bytes(attest))
    except ValueError as e:
        return [str(e)]
    if extra.hex() != nonce:
        problems.append("the quote is not over this challenge's nonce (replayed?)")
    key = ec.EllipticCurvePublicNumbers(int(quote["ak_x"], 16), int(quote["ak_y"], 16), ec.SECP256R1()).public_key()
    signature = encode_dss_signature(int(quote["sig_r"], 16), int(quote["sig_s"], 16))
    try:
        key.verify(signature, bytes(attest), ec.ECDSA(hashes.SHA256()))
    except InvalidSignature:
        problems.append("the signature does not verify")
    if selected != PCRS:
        problems.append(f"quoted PCRs {selected}, expected {PCRS}")
    reported = b"".join(bytes.fromhex(quote["pcrs"][p]) for p in PCRS)
    if hashlib.sha256(reported).digest() != pcr_digest:
        problems.append("the reported PCR values are not the ones the TPM signed")
    pcr12 = bytes(32)
    for entry in quote["log"]:
        pcr12 = hashlib.sha256(pcr12 + bytes.fromhex(entry["digest"])).digest()
    if pcr12.hex() != quote["pcrs"]["12"]:
        problems.append("the measurement log does not replay to PCR 12")
    return problems


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--log", default="build/telemetry.log")
    p.add_argument("--record", metavar="REF")
    p.add_argument("--expected-pcr12")
    p.add_argument("--reference", metavar="REF")
    p.add_argument("--nonce", help="check against this nonce instead of the logged challenge")
    p.add_argument("--tamper", action="store_true", help="flip a bit of the quote first (tests)")
    args = p.parse_args()
    if bool(args.record) == bool(args.reference):
        sys.exit("give --record or --reference")

    records = []
    for line in open(args.log, encoding="utf-8", errors="replace"):
        try:
            records.append(json.loads(line))
        except ValueError:
            pass
    quote = last(records, "quote")
    nonce = args.nonce or last(records, "challenge")["nonce"]
    problems = check(quote, nonce, args.tamper)

    if args.record:
        if not args.expected_pcr12:
            sys.exit("--record needs --expected-pcr12 (tools/expected-pcrs.py)")
        if quote["pcrs"]["12"] != args.expected_pcr12:
            problems.append("PCR 12 is not what the approved build measures to")
        if not problems:
            reference = {"ak_x": quote["ak_x"], "ak_y": quote["ak_y"],
                         "pcrs": {p: quote["pcrs"][p] for p in ["0", "4", "7"]} | {"12": args.expected_pcr12}}
            with open(args.record, "w") as f:
                json.dump(reference, f, indent=2)
    else:
        reference = json.load(open(args.reference))
        if (quote["ak_x"], quote["ak_y"]) != (reference["ak_x"], reference["ak_y"]):
            problems.append("signed by a different attestation key than the reference")
        for pcr, want in reference["pcrs"].items():
            if quote["pcrs"][pcr] != want:
                what = {"0": "firmware", "4": "boot loader", "7": "Secure Boot state", "12": "kernel/manifest/tasks"}[pcr]
                problems.append(f"PCR {pcr} ({what}) differs from the reference")

    for problem in problems:
        print(f"verify-quote: FAIL: {problem}")
    if problems:
        sys.exit(1)
    print(f"verify-quote: OK ({'recorded' if args.record else 'matches'} reference; nonce {nonce[:16]}..., "
          f"PCR12 {quote['pcrs']['12'][:16]}...)")


if __name__ == "__main__":
    main()
